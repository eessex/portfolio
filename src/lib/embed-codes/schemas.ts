import { z } from 'zod'

import {
  baseContentSchema,
  baseEmbeddedItemSlugsSchema,
  longText,
  shortText
} from '@/lib/schemas'

/**
 * The variety of media displayed in an iframe embed.
 */
export const embedCodeTypes = ['audio', 'video'] as const
export type EmbedCodeType = (typeof embedCodeTypes)[number]

/**
 * The type of content depicted in the embed.
 * TODO: DB migration to add this column.
 */
export const embedCodeContentTypes = [
  'dj_set',
  'documentation',
  'interview',
  'film',
  'live_performance',
  'official_audio',
  'official_music_video',
  'other',
  'podcast',
  'radio_show',
  'trailer'
] as const

export const audioEmbedCodeHosts = [
  'bandcamp',
  'mixcloud',
  'soundcloud',
  'spotify'
] as const

export const videoEmbedCodeHosts = ['vimeo', 'youtube'] as const

export const embedCodeHosts = [
  ...audioEmbedCodeHosts,
  ...videoEmbedCodeHosts,
  'unknown'
] as const
export type EmbedCodeHost = (typeof embedCodeHosts)[number]

const embedCodeBaseSchema = z.lazy(() =>
  z.object({
    caption: shortText.optional(),
    host: z.enum(embedCodeHosts),
    iframe: longText.min(12),
    src: z.string().url(),
    type: z.enum(embedCodeTypes)
  })
)

/**
 * An iframe embed code, such as a Bandcamp or YouTube embed, with metadata.
 */
export const embedCodeSchema = z.lazy(() =>
  baseContentSchema.and(embedCodeBaseSchema)
)

/**
 * Omits fields that are auto-generated by the database.
 */
export const editEmbedCodeSchema = z.lazy(() =>
  baseContentSchema
    .omit({
      createdAt: true,
      updatedAt: true
    })
    .and(embedCodeBaseSchema)
)

export const createEmbedCodeSchema = z.lazy(() =>
  baseContentSchema
    .omit({
      id: true,
      createdAt: true,
      updatedAt: true
    })
    .and(embedCodeBaseSchema)
)

/**
 * Extends `embedCodeSchema` with the pages that embed it.
 */
export const dashboardEmbedCodeSchema = z.lazy(() =>
  baseEmbeddedItemSlugsSchema.and(embedCodeSchema)
)
