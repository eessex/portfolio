import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { shortText, uuid } from '@/lib/schemas/primitives'

/**
 * The variety of media displayed in an iframe embed.
 */
export const embedCodeTypes = ['video', 'audio'] as const
export const embedCodeTypesSchema = z.enum(embedCodeTypes)
export const EmbedCodeTypes = Object.fromEntries(
  embedCodeTypes.map((v) => [v, v])
) as {
  [K in (typeof embedCodeTypes)[number]]: K
}
export type EmbedCodeType = z.infer<typeof embedCodeTypesSchema>

/**
 * The type of content depicted in the embed. Split by whether it's
 * video-only (hidden from the picker when the embed's `type` is
 * `audio`) or applicable regardless of `type`.
 */
export const EmbedCodeContentTypesByType = {
  video: ['film', 'official_music_video', 'trailer'],
  shared: [
    'dj_set',
    'documentation',
    'interview',
    'live_performance',
    'official_audio',
    'other',
    'podcast',
    'radio_show'
  ]
} as const
export const embedCodeContentTypes = [
  ...EmbedCodeContentTypesByType.video,
  ...EmbedCodeContentTypesByType.shared
] as const
export const embedCodeContentTypeSchema = z.enum(
  embedCodeContentTypes
)
export const EmbedCodeContentTypes = Object.fromEntries(
  embedCodeContentTypes.map((v) => [v, v])
) as {
  [K in (typeof embedCodeContentTypes)[number]]: K
}
export type EmbedCodeContentType = z.infer<
  typeof embedCodeContentTypeSchema
>

export const EmbedCodeHostsByType = {
  audio: ['bandcamp', 'mixcloud', 'soundcloud', 'spotify'],
  video: ['vimeo', 'youtube']
} as const
export const embedCodeHosts = [
  ...EmbedCodeHostsByType.audio,
  ...EmbedCodeHostsByType.video,
  'unknown'
] as const
export const EmbedCodeHosts = Object.fromEntries(
  embedCodeHosts.map((v) => [v, v])
) as {
  [K in (typeof embedCodeHosts)[number]]: K
}
export const embedCodeHostSchema = z.enum(embedCodeHosts)
export type EmbedCodeHost = z.infer<typeof embedCodeHostSchema>

const embedCodeFields = {
  caption: shortText.optional(),
  contentType: embedCodeContentTypeSchema.optional(),
  coverImageId: uuid.optional(),
  host: embedCodeHostSchema,
  /** @deprecated use src */
  iframe: z.string().optional(),
  src: z.string().url().min(5).max(1000),
  title: shortText.optional(),
  type: embedCodeTypesSchema
}

/**
 * An iframe embed code, such as a Bandcamp or YouTube embed, with metadata.
 */
export const embedCodeSchema = z.object({
  ...systemFields,
  ...embedCodeFields
})
export type EmbedCode = z.infer<typeof embedCodeSchema>

/**
 * Omits fields that are auto-generated by the database.
 */
export const createEmbedCodeSchema = z.object({
  ...embedCodeFields
})
export type CreateEmbedCode = z.infer<typeof createEmbedCodeSchema>
