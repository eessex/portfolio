import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { bool, shortText, url } from '@/lib/schemas/primitives'

const imageFields = {
  alt: shortText.optional(),
  aspect: z.preprocess((val) => {
    if (typeof val === 'number') {
      return Number(val.toFixed(4))
    }
    if (typeof val === 'string') {
      const num = parseFloat(val)
      return isNaN(num) ? val : Number(num.toFixed(4))
    }
    return val
  }, z.number().min(0.1).max(10)),
  caption: shortText.optional(),
  isHiddenOnAboutPage: bool.optional(),
  isPress: bool.optional(),
  title: shortText.optional(),
  url
}

/**
 * An image with metadata.
 */
export const imageSchema = z.object({
  ...systemFields,
  ...imageFields
})
export type Image = z.infer<typeof imageSchema>

/**
 * Omits fields that are auto-generated by the database.
 */
export const createImageSchema = z.object({
  ...imageFields
})
export type CreateImage = z.infer<typeof createImageSchema>
