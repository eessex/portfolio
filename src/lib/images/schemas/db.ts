import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { shortText, url, uuid } from '@/lib/schemas/primitives'
import { imageKey, publicUrl } from '@/lib/storage/keys'

/**
 * The category of an image.
 */
export const imageTypes = [
  'press',
  'documentation',
  'flyer',
  'artwork'
] as const
export const imageTypeSchema = z.enum(imageTypes)
export const ImageTypes = Object.fromEntries(
  imageTypes.map((v) => [v, v])
) as {
  [K in (typeof imageTypes)[number]]: K
}
export type ImageType = z.infer<typeof imageTypeSchema>

/**
 * An original's format, as sharp names it; sets its key's extension.
 * The keys of `uploadFormats`.
 */
export const imageFormats = ['jpeg', 'png', 'webp', 'gif'] as const
export const imageFormatSchema = z.enum(imageFormats)
export type ImageFormat = z.infer<typeof imageFormatSchema>

/**
 * Filled from the file on upload, never from the form. Empty on rows
 * saved before Stage 3, until the storage copy records them.
 */
const storedFileFields = {
  format: imageFormatSchema.optional(),
  width: z.number().int().positive().optional(),
  height: z.number().int().positive().optional(),
  originalFilename: shortText.optional(),
  contentHash: z.string().optional(),
  blurDataUrl: z.string().optional(),
  variantVersion: z.number().int().min(0).optional()
}
export const storedFileFieldNames = Object.keys(
  storedFileFields
) as (keyof typeof storedFileFields)[]

const imageFields = {
  alt: shortText.optional(),
  aspect: z.preprocess((val) => {
    if (typeof val === 'number') {
      return Number(val.toFixed(4))
    }
    if (typeof val === 'string') {
      const num = parseFloat(val)
      return isNaN(num) ? val : Number(num.toFixed(4))
    }
    return val
  }, z.number().min(0.1).max(10)),
  caption: shortText.optional(),
  type: imageTypeSchema.optional(),
  title: shortText.optional(),
  url,
  ...storedFileFields
}

/**
 * A row with a format is served from `images/{id}.{ext}` on the active
 * provider; older rows fall back to their stored url. Runs on the
 * server, where fetched rows are parsed.
 */
export function withPublicUrl<
  T extends { id: string; url: string; format?: string }
>(image: T): T {
  if (!image.format) return image
  return {
    ...image,
    url: publicUrl(imageKey(image.id, image.format))
  }
}

export const imageObjectSchema = z.object({
  ...systemFields,
  ...imageFields
})

/**
 * An image with metadata.
 */
export const imageSchema = imageObjectSchema.transform(withPublicUrl)
export type Image = z.infer<typeof imageSchema>

/**
 * Omits fields that are auto-generated by the database. `id` is set
 * only by an upload, which issues it before storing the file.
 */
export const createImageSchema = z.object({
  id: uuid.optional(),
  ...imageFields
})
export type CreateImage = z.infer<typeof createImageSchema>

/**
 * In forms, `url` is only known on the server after the file is
 * uploaded, and the stored file's fields come from the file itself.
 */
export const imageClientFieldsSchema = createImageSchema.omit({
  id: true,
  url: true,
  format: true,
  width: true,
  height: true,
  originalFilename: true,
  contentHash: true,
  blurDataUrl: true,
  variantVersion: true
})
