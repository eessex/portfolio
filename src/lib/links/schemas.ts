import { z } from 'zod'

import {
  baseContentSchema,
  baseEmbeddedItemSlugsSchema,
  bool,
  date,
  shortText,
  url
} from '@/lib/schemas'

export const linkTypes = [
  'press',
  'social',
  'buy_link',
  'stream_link'
] as const

const linksBaseSchema = z.lazy(() =>
  z.object({
    attribution: shortText.optional(),
    isHiddenOnAboutPage: bool.optional(),
    publishDate: date.optional(),
    quotation: shortText.optional(),
    type: z.preprocess(
      (val) => (val === '' ? undefined : val),
      z.enum(linkTypes).optional()
    ),
    url
  })
)

/**
 * A link to an external resource with metadata.
 */
export const linkSchema = z.lazy(() =>
  baseContentSchema.and(linksBaseSchema)
)

/**
 * Omits fields that are auto-generated by the database.
 */
export const editLinkSchema = z.lazy(() =>
  baseContentSchema.omit({ createdAt: true }).and(linksBaseSchema)
)

export const createLinkSchema = z.lazy(() =>
  baseContentSchema
    .omit({
      id: true,
      createdAt: true,
      updatedAt: true
    })
    .and(linksBaseSchema)
)

/**
 * Extends `linkSchema` with the pages that embed it.
 */
export const dashboardLinkSchema = z.lazy(() =>
  baseEmbeddedItemSlugsSchema.and(linkSchema)
)
