import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { bool, date, shortText, url } from '@/lib/schemas/primitives'

/**
 * The category of resource a link points to.
 */
export const linkTypes = [
  'press',
  'social',
  'buy_link',
  'stream_link'
] as const
export const linkTypeSchema = z.enum(linkTypes)
export const LinkTypes = Object.fromEntries(
  linkTypes.map((v) => [v, v])
) as {
  [K in (typeof linkTypes)[number]]: K
}
export type LinkType = z.infer<typeof linkTypeSchema>

const linkFields = {
  attribution: shortText.optional(),
  isHiddenOnAboutPage: bool.optional(),
  publishDate: date.optional(),
  quotation: shortText.optional(),
  title: shortText.optional(),
  type: linkTypeSchema.optional(),
  url
}

/**
 * A link to an external resource with metadata.
 */
export const linkSchema = z.object({
  ...systemFields,
  ...linkFields
})
export type Link = z.infer<typeof linkSchema>

/**
 * Omits fields that are auto-generated by the database.
 */
export const createLinkSchema = z.object({
  ...linkFields
})
export type CreateLink = z.infer<typeof createLinkSchema>

/**
 * A link created or edited from the Press picker, which requires the
 * citation fields its layout shows.
 */
export const createPressLinkSchema = createLinkSchema.extend({
  attribution: shortText,
  publishDate: date,
  title: shortText
})
