import { z } from 'zod'

import { embedCodeSchema } from '@/lib/embed-codes/schemas/db'
import { imageSchema } from '@/lib/images/schemas/db'
import { linkSchema } from '@/lib/links/schemas/db'
import { publisherSchema } from '@/lib/publishers/schemas/db'
import { PagePaths } from '@/lib/schemas'
import {
  contactFields,
  contentFields,
  relationFields,
  systemFields,
  taxonomyFields
} from '@/lib/schemas/fields'
import { date, uuid } from '@/lib/schemas/primitives'

export const projectTypes = [
  'band',
  'collaborative',
  'eventSeries',
  'radioShow',
  'recordLabel',
  'solo'
] as const
export const projectTypeSchema = z.enum(projectTypes)
export const ProjectTypes = Object.fromEntries(
  projectTypes.map((v) => [v, v])
) as {
  [K in (typeof projectTypes)[number]]: K
}
export type ProjectType = z.infer<typeof projectTypeSchema>

/**
 * Project types that are an artist (a label site's roster); every
 * other type is a non-artist project (an imprint, event series or
 * radio show). Derived from the type, so changing it moves a project
 * between roles with no data change.
 */
export const artistProjectTypes = [
  ProjectTypes.band,
  ProjectTypes.solo,
  ProjectTypes.collaborative
] as const satisfies readonly ProjectType[]

/** How a project list is ordered: by date (the default), or by name */
export const projectsOrderBys = ['date', 'name'] as const
export type ProjectsOrderBy = (typeof projectsOrderBys)[number]

export function isArtistProjectType(type?: ProjectType) {
  return (
    !!type &&
    (artistProjectTypes as readonly ProjectType[]).includes(type)
  )
}

/**
 * Represents a grouping of content that may be associated with multiple events, releases or embedCodes.
 * Can represent a band, collaborative, or other entities like an ongoing radio show or event series.
 * It may be used to suggest content on pages, similar to a tag, but with a broader scope.
 *
 * At most one project is the site's default (`isDefaultProject`),
 * rendered at /about; the rest each represent a subset of the site's work.
 */
export const projectSchema = z.object({
  ...systemFields,
  ...taxonomyFields,
  ...contentFields,
  ...contactFields,
  coverImageId: relationFields.coverImageId,
  embedCodeIds: relationFields.embedCodeIds,
  endDate: date.optional(),
  imageIds: relationFields.imageIds,
  /**
   * The project rendered at `/about`; at most one (partial unique index).
   * Set only by the default-project action, never submitted by the form,
   * kept on every update.
   */
  isDefaultProject: z.boolean().optional(),
  linkIds: relationFields.linkIds,
  path: z.literal(PagePaths.projects).default(PagePaths.projects),
  /**
   * A `recordLabel` project's own publisher (unique across projects):
   * the default project's is the site's house publisher. Cleared on
   * save for any other type.
   */
  publisherId: uuid.optional(),
  startDate: date.optional(),
  type: projectTypeSchema.optional()
})

/**
 * Extends `projectSchema` embedded item metadata.
 */
export const projectClientSchema = projectSchema.extend({
  coverImage: z.lazy(() => imageSchema).optional(),
  embedCodes: z.lazy(() => embedCodeSchema.array()).optional(),
  hasAudio: z.boolean().optional(),
  hasVideo: z.boolean().optional(),
  images: z.lazy(() => imageSchema.array()).optional(),
  links: z.lazy(() => linkSchema.array()).optional(),
  publisher: publisherSchema.optional()
})

/**
 * Omits fields that are auto-generated by the database. `slug` is
 * kept required here (generated server-side from `title` in
 * `editProject`'s `prepare` hook, not submitted by the form). `type`
 * is required on save for every project, the default one included
 * (`/about` just doesn't display it); `projectSchema` keeps it optional
 * so older rows without one still read. `startDate` stays optional
 * here: it's required only where `isProjectDateShown()`, which depends
 * on the site kind, so `prepare` enforces it.
 */
export const createProjectSchema = projectSchema
  .omit({
    id: true,
    createdAt: true,
    updatedAt: true
  })
  .extend({
    type: projectTypeSchema
  })

/**
 * `createProjectSchema` wherever project dates show
 * (`isProjectDateShown`): the start date is required.
 */
export const createDatedProjectSchema = createProjectSchema.extend({
  startDate: date
})
