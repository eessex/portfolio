import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { bool, shortText, url } from '@/lib/schemas/primitives'

/** The built-in publisher `pnpm run setup` creates (or adopts). */
export const SELF_RELEASED_PUBLISHER_NAME = 'Self-released'

export const publisherTypes = [
  'recordLabel',
  'publishingHouse',
  'museum'
] as const
export const publisherTypeSchema = z.enum(publisherTypes)
export const PublisherTypes = Object.fromEntries(
  publisherTypes.map((v) => [v, v])
) as {
  [K in (typeof publisherTypes)[number]]: K
}
export type PublisherType = z.infer<typeof publisherTypeSchema>

const publisherFields = {
  name: shortText,
  url: url.optional(),
  type: publisherTypeSchema.optional()
}

/**
 * A record label, publishing house, or museum that publishes or
 * distributes a release's editions.
 */
export const publisherSchema = z.object({
  ...systemFields,
  ...publisherFields,
  // set only by setup; read-only and listed first
  isBuiltIn: bool.optional()
})
export type Publisher = z.infer<typeof publisherSchema>

/**
 * Omits fields that are auto-generated by the database.
 */
export const createPublisherSchema = z.object({
  ...publisherFields
})
export type CreatePublisher = z.infer<typeof createPublisherSchema>
