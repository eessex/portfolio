import { z } from 'zod'

import {
  baseEmbeddedItemSlugsSchema,
  defaultSchema,
  shortText,
  url,
  uuid
} from '@/lib/schemas'

const venueBaseSchema = z.lazy(() =>
  z.object({
    address: shortText.optional(),
    city: shortText,
    name: shortText.optional(),
    state: shortText.optional(),
    country: shortText.optional(),
    url: url.optional(),
    timezone: shortText.max(100).optional(),
    primaryVenueId: uuid.optional()
  })
)

/**
 * A venue where an event or exhibition takes place.
 */
export const venueSchema = z.lazy(() =>
  defaultSchema.and(venueBaseSchema)
)

/**
 * Omits fields that are auto-generated by the database.
 */
export const editVenueSchema = z.lazy(() =>
  defaultSchema.omit({ createdAt: true }).and(venueBaseSchema)
)

export const createVenueSchema = z.lazy(() =>
  defaultSchema
    .omit({
      id: true,
      createdAt: true,
      updatedAt: true
    })
    .and(venueBaseSchema)
)

/**
 * Extends `venueSchema` with the pages that embed it.
 */
export const dashboardVenueSchema = z.lazy(() =>
  baseEmbeddedItemSlugsSchema.and(venueSchema)
)
