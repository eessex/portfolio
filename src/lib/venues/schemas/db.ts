import { z } from 'zod'

import { systemFields } from '@/lib/schemas/fields'
import { shortText, url, uuid } from '@/lib/schemas/primitives'

/**
 * A curated subset of IANA timezones, roughly one per region, biased
 * toward the US and Europe. Avoids listing every zone (e.g. the 3
 * covering North Dakota) that shares an offset with a more common one,
 * except where multiple cities in the same zone are common enough
 * (e.g. Paris and Berlin) that listing both aids recognition.
 */
export const venueTimezones = [
  // North America
  'Pacific/Honolulu',
  'America/Anchorage',
  'America/Los_Angeles',
  'America/Denver',
  'America/Chicago',
  'America/New_York',
  'America/Halifax',
  // Central & South America
  'America/Mexico_City',
  'America/Bogota',
  'America/Sao_Paulo',
  // Europe
  'Atlantic/Reykjavik',
  'Europe/London',
  'Europe/Paris',
  'Europe/Berlin',
  'Europe/Helsinki',
  'Europe/Istanbul',
  'Europe/Moscow',
  // Africa & Middle East
  'Africa/Lagos',
  'Africa/Cairo',
  'Africa/Johannesburg',
  'Asia/Dubai',
  // Asia
  'Asia/Kolkata',
  'Asia/Bangkok',
  'Asia/Shanghai',
  'Asia/Tokyo',
  'Asia/Seoul',
  // Oceania
  'Australia/Perth',
  'Australia/Sydney',
  'Pacific/Auckland'
] as const
export const venueTimezoneSchema = z.enum(venueTimezones)
export type VenueTimezone = z.infer<typeof venueTimezoneSchema>

const venueFields = {
  address: shortText.optional(),
  city: shortText,
  country: shortText.optional(),
  name: shortText.optional(),
  primaryVenueId: uuid.optional(),
  state: shortText.optional(),
  timezone: venueTimezoneSchema,
  url: url.optional()
}

/**
 * A venue where an event or exhibition takes place.
 */
export const venueSchema = z.object({
  ...systemFields,
  ...venueFields
})
export type Venue = z.infer<typeof venueSchema>

/**
 * Omits fields that are auto-generated by the database.
 */
export const createVenueSchema = z.object({
  ...venueFields
})
export type CreateVenue = z.infer<typeof createVenueSchema>
